export function computeWaveCalmPercent(zone, barrierChoice) {
  if (!zone || barrierChoice === 'none') return 0;
  if (barrierChoice === 'rock') {
    return zone.wave_intensity >= 5 ? 95 : 100;
  }
  if (barrierChoice === 'bamboo') {
    if (zone.wave_intensity >= 5) return 58;
    if (zone.wave_intensity >= 3) return 72;
    return 84;
  }
  return 0;
}

export function computeLandRecoveredSqm({ hasUserTree, growthProgress, zone }) {
  if (!hasUserTree) return 0;
  const zoneFactor = zone ? 0.9 + zone.wave_intensity * 0.08 : 1;
  const growthFactor = 0.35 + growthProgress * 1.15;
  return Number((3.2 * zoneFactor * growthFactor).toFixed(1));
}
